export interface ParamDecoratorRule {
    name: string;
    decorator: () => ParameterDecorator;
    /** Request header the decorator reads; the handler depends on it, so it is required unless stated otherwise. */
    header?: HeaderRead;
    /** Value derived from authentication or scope resolution, not sent by the client. */
    derived?: string;
}

