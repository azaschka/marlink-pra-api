/**
 * Classification of every guard, interceptor, pipe and custom parameter decorator that can appear on a
 * PRA API route, and the request inputs each of them reads.
 *
 * The generator refuses to run when a route uses a component that is not listed here: a new guard or pipe
 * may introduce a new credential or header, and that has to be documented deliberately.
 */

export interface HeaderRead {
    name: string;
    required: boolean;
    type: 'string' | 'integer' | 'boolean';
    description: string;
}

export type ComponentRole =
    | 'authentication'
    | 'authorization'
    | 'validation'
    | 'non-empty-body'
    | 'observability'
    | 'scope';

export interface ComponentRule {
    role: ComponentRole;
    authScheme?: AuthScheme;
    readsHeaders?: HeaderRead[];
    /** Human readable rule shown in the request documentation. */
    note?: string;
}

